#!/usr/bin/env python3
"""Disposable P5 end-to-end proof. Requires built jars, JDK 25, Docker and network for image pulls.
All JVM identities/data are generated by hardening_drill; no Compose application volumes are touched.
"""
import argparse
import base64
import json
import math
import os
import signal
from pathlib import Path
import socket
import subprocess
import tempfile
import time
import urllib.parse
import urllib.error
import urllib.request
import uuid

ROOT = Path(__file__).resolve().parents[2]
HTTP = urllib.request.build_opener(urllib.request.ProxyHandler({}))


def free_port():
    with socket.socket() as sock:
        sock.bind(('127.0.0.1', 0))
        return sock.getsockname()[1]


def request(port, path, password=None):
    headers = {'Accept': 'application/json'}
    if password:
        headers['Authorization'] = 'Basic ' + base64.b64encode(('admin:' + password).encode()).decode()
    with HTTP.open(urllib.request.Request(f'http://127.0.0.1:{port}{path}', headers=headers), timeout=5) as response:
        body = response.read()
        return json.loads(body) if body[:1] in (b'{', b'[') else body.decode()


def query(port, expression):
    result = request(port, '/api/v1/query?' + urllib.parse.urlencode({'query': expression}))
    if result.get('status') != 'success':
        raise RuntimeError('Prometheus query failed')
    return result['data']['result']


def trace_services(value):
    found = set()
    if isinstance(value, dict):
        if value.get('key') == 'service.name':
            found.add(value.get('value', {}).get('stringValue'))
        for child in value.values():
            found.update(trace_services(child))
    elif isinstance(value, list):
        for child in value:
            found.update(trace_services(child))
    return found


def verify(state, fixture_root, config_only=False):
    ports, work = state['ports'], Path(state['work'])
    env = {**os.environ, **state['values']}
    compose = state['compose']
    for key, path in [('OTEL_HEALTH_PORT', '/'), ('PROMETHEUS_PORT', '/-/ready'), ('LOKI_PORT', '/ready'),
                      ('TEMPO_PORT', '/ready'), ('GRAFANA_PORT', '/api/health'), ('ALERTMANAGER_PORT', '/-/ready')]:
        for attempt in range(90):
            try:
                request(ports[key], path)
                break
            except Exception:
                if attempt == 89:
                    raise RuntimeError('Stack health check failed: ' + key)
                time.sleep(1)
    with (work / 'promtool.log').open('w') as output:
        subprocess.run([*compose, 'exec', '-T', 'prometheus', 'promtool', 'check', 'rules', '/etc/prometheus/alerts-p5.yml'], env=env, stdout=output, stderr=output, check=True)
    with (work / 'alert-unit-tests.log').open('w') as output:
        subprocess.run([*compose, 'run', '--rm', '--no-deps', '--entrypoint', '/bin/promtool', '-v', str(ROOT / 'infra/observability') + ':/rules:ro', '-w', '/rules', 'prometheus', 'test', 'rules', 'alert-tests.yml'], env=env, stdout=output, stderr=output, check=True)
    dashboard = request(ports['GRAFANA_PORT'], '/api/dashboards/uid/hybrid-p5', state['password'])
    assert len(dashboard['dashboard']['panels']) >= 12, 'Dashboard not provisioned'
    for source in ('prometheus', 'loki', 'tempo'):
        health = request(ports['GRAFANA_PORT'], f'/api/datasources/uid/{source}/health', state['password'])
        assert health['status'] == 'OK', 'Grafana datasource failed: ' + source
    for panel in dashboard['dashboard']['panels']:
        expression=panel['targets'][0]['expr'].replace('$application', '.+')
        if panel['datasource']['uid']=='prometheus':
            query(ports['PROMETHEUS_PORT'],expression)
        elif panel['datasource']['uid']=='loki':
            request(ports['LOKI_PORT'],'/loki/api/v1/query_range?'+urllib.parse.urlencode({'query':expression,'limit':1}))
    # Exercise Collector privacy on an actual exported span, including exception events.
    probe_trace=uuid.uuid4().hex
    now=str(time.time_ns())
    payload={'resourceSpans':[{'resource':{'attributes':[{'key':'service.name','value':{'stringValue':'p5-probe'}}]},
        'scopeSpans':[{'spans':[{'traceId':probe_trace,'spanId':uuid.uuid4().hex[:16],'name':'privacy-check',
            'startTimeUnixNano':now,'endTimeUnixNano':str(int(now)+1000000),
            'attributes':[{'key':'url.full','value':{'stringValue':'http://example.test/?secret=private-test-marker'}}],
            'events':[{'name':'exception','timeUnixNano':now,'attributes':[{'key':'exception.message','value':{'stringValue':'private-test-marker'}},{'key':'exception.stacktrace','value':{'stringValue':'private-test-marker'}}]}]}]}]}]}
    with HTTP.open(urllib.request.Request(f'http://127.0.0.1:{ports["OTEL_HTTP_PORT"]}/v1/traces',
            data=json.dumps(payload).encode(),headers={'Content-Type':'application/json'}),timeout=5) as response:
        assert response.status==200
    for attempt in range(20):
        try:
            exported=request(ports['TEMPO_PORT'],'/api/traces/'+probe_trace)
            assert 'private-test-marker' not in json.dumps(exported),'Sensitive exception or URL attribute reached Tempo'
            break
        except urllib.error.HTTPError:
            if attempt==19:raise
            time.sleep(1)
    if config_only:
        print("P5 config passed: backend health, Grafana provisioning, all dashboard queries and alert rule tests.",flush=True)
        return
    correlation = str(uuid.uuid4())
    settings = {**env, 'OBSERVABILITY_ENABLED': 'true', 'TRACING_SAMPLE_PROBABILITY': '1.0',
                'OTEL_EXPORTER_OTLP_TRACES_ENDPOINT': f'http://127.0.0.1:{ports["OTEL_HTTP_PORT"]}/v1/traces',
                'OTEL_EXPORTER_OTLP_METRICS_ENDPOINT': f'http://127.0.0.1:{ports["OTEL_HTTP_PORT"]}/v1/metrics',
                'METRICS_EXPORT_STEP': '2s', 'TELEMETRY_LOG_PATH': str(work / 'telemetry'), 'P5_PROBE_ID': correlation}
    observed, trace_id, services = set(), None, set()
    expressions = ['auth_login_attempts_total', 'http_server_requests_seconds_bucket', 'auth_active_sessions',
                   'auth_refresh_reuse_detected_total', 'auth_redis_connection_failures_total']
    with (work / 'services.log').open('w') as output:
        fixture = subprocess.Popen(['python3', '-u', str(fixture_root / 'scripts/verification/hardening_drill.py')],
                                   cwd=fixture_root, env=settings, stdout=output, stderr=output)
        try:
            deadline = time.monotonic() + 420
            while time.monotonic() < deadline:
                for metric in expressions:
                    values = query(ports['PROMETHEUS_PORT'], metric)
                    if any(math.isfinite(float(row['value'][1])) for row in values):
                        if metric in ('auth_refresh_reuse_detected_total', 'auth_redis_connection_failures_total'):
                            if any(float(row['value'][1]) > 0 for row in values):
                                observed.add(metric)
                        else:
                            observed.add(metric)
                # The same request ID must resolve to one distributed trace across all three services.
                for path in (work / 'telemetry').glob('*.jsonl'):
                    for line in path.read_text().splitlines():
                        try:
                            entry = json.loads(line)
                            if entry.get('correlation_id') == correlation and entry.get('trace_id'):
                                trace_id = entry['trace_id']
                        except ValueError:
                            continue
                if trace_id:
                    try:
                        services = trace_services(request(ports['TEMPO_PORT'], '/api/traces/' + trace_id))
                    except Exception:
                        pass
                if fixture.poll() is not None:
                    assert fixture.returncode == 0, 'Service drill failed; see ' + str(work / 'services.log')
                    if len(observed) == len(expressions) and {'api-gateway', 'auth-service', 'user-service'} <= services:
                        break
                time.sleep(3)
            else:
                raise RuntimeError(f'Telemetry proof incomplete: metrics={sorted(observed)}, trace services={sorted(str(s) for s in services)}; logs at {work}')
        finally:
            if fixture.poll() is None:
                fixture.send_signal(signal.SIGINT)
                try:
                    fixture.wait(timeout=45)
                except subprocess.TimeoutExpired:
                    fixture.kill()
                    fixture.wait()
    expression = '{service_name="api-gateway"} |= "' + correlation + '"'
    result = request(ports['LOKI_PORT'], '/loki/api/v1/query_range?' + urllib.parse.urlencode({'query': expression, 'limit': 100, 'start': str(time.time_ns() - 900_000_000_000)}))
    assert result['data']['result'], 'Correlated gateway log did not reach Loki'
    alerts = request(ports['PROMETHEUS_PORT'], '/api/v1/alerts')['data']['alerts']
    assert any(a['labels']['alertname'] == 'HybridRefreshTokenReplay' for a in alerts), 'Replay alert did not activate'
    output=ROOT/'reports'/'observability';output.mkdir(parents=True,exist_ok=True)
    (output/'result.json').write_text(json.dumps({'status':'passed','metrics':sorted(observed),'trace_services':sorted(str(s) for s in services),'grafana_dashboard':'hybrid-p5','correlated_logs':True,'refresh_replay_alert':True},indent=2)+'\n')
    print('P5 passed: metrics and histograms in Prometheus, correlated logs in Loki, Gateway/Auth/User trace in Tempo, Grafana dashboard/datasources, refresh replay alert and Redis failure counter.', flush=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config-only",action="store_true",help="Validate stack, dashboard queries and alert rules without starting Java fixtures")
    args=parser.parse_args()
    # Reusing an agent-created temporary stack is useful while iterating; normal runs create their own.
    reuse = os.environ.get('P5_STACK_STATE')
    if reuse:
        state = json.loads(Path(reuse).read_text())
    else:
        work = Path(tempfile.mkdtemp(prefix='p5-drill-'))
        (work / 'telemetry').mkdir()
        values = {key: str(free_port()) for key in ['OTEL_HTTP_PORT', 'OTEL_HEALTH_PORT', 'PROMETHEUS_PORT', 'LOKI_PORT', 'TEMPO_PORT', 'ALERTMANAGER_PORT', 'GRAFANA_PORT']}
        password = 'test-' + uuid.uuid4().hex
        values['GRAFANA_ADMIN_PASSWORD'] = password
        override = work / 'override.json'
        override.write_text(json.dumps({'services': {'otel-collector': {'volumes': [{'type': 'bind', 'source': str(work / 'telemetry'), 'target': '/var/log/hybrid', 'read_only': True}]}}}))
        state = {'work': str(work), 'project': 'p5-verify-' + uuid.uuid4().hex[:8], 'password': password,
                 'values': values, 'ports': {k: int(v) for k, v in values.items() if k.endswith('_PORT')}}
        state['compose'] = ['docker', 'compose', '-p', state['project'], '-f', str(ROOT / 'compose.observability.yaml'), '-f', str(override)]
    if not state['project'].startswith('p5-verify-'):
        raise RuntimeError('Refusing to mutate a non-test Compose project')
    env = {**os.environ, **state['values']}
    print('Temporary P5 diagnostics: '+state['work'],flush=True)
    try:
        subprocess.run([*state['compose'], 'up', '-d'], env=env, check=True)
        verify(state, Path(os.environ.get('P5_FIXTURE_ROOT', str(ROOT))),args.config_only)
    finally:
        # Retain diagnostic files in /tmp; only this disposable project's containers/volumes are deleted.
        subprocess.run([*state['compose'], 'down', '-v'], env=env, check=True)


def interrupted(signum, frame):
    raise KeyboardInterrupt


if __name__ == '__main__':
    signal.signal(signal.SIGTERM, interrupted)
    main()
